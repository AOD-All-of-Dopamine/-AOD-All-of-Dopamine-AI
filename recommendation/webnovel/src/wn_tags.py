_C = {t: re.compile(p) for t, p in TAGS.items()}

def tag_text(title: str, synopsis: str, genre: str = "", max_tags: int = 5):
    txt = f"{title or ''} {synopsis or ''}"
    hits = []
    for t, c in _C.items():
        n = len(c.findall(txt))
        if n: hits.append((n, t))
    hits.sort(reverse=True)
    return [t for _, t in hits[:max_tags]]

def build_semantic_text(row, max_tags: int = 5) -> str:
    tags = tag_text(row["name"], row["synopsis"], max_tags=max_tags)
    genre = "/".join(row["genres"]) if row["genres"] is not None and len(row["genres"]) else ""
    head = f"장르: {genre}"
    if tags: head += f" | 태그: {', '.join(tags)}"
    syn = (row["synopsis"] or "")[:600]
    return f"{head}\n제목: {row['name']}\n줄거리: {syn}"
